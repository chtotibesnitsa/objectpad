import { chromium } from 'playwright';
const base = 'https://pdud1tb5ce6u6kv0hgpfl-web-handlesend.rork.live';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1600, height: 1000 } })).newPage();
p.on('pageerror', e => console.log('ERR', e.message.slice(0, 200)));
await p.goto(base + '/v2', { waitUntil: 'domcontentloaded', timeout: 40000 });
await p.waitForTimeout(7000);
await p.screenshot({ path: '/home/user/rork-app/zz-a.png' });
await p.evaluate(() => window.scrollTo(0, 1250)); await p.waitForTimeout(2500);
await p.screenshot({ path: '/home/user/rork-app/zz-b.png' });
await b.close();
